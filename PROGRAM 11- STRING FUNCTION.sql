-- UPPER
SELECT UPPER(NAME) FROM PERSON;


-- LOWER
SELECT LOWER(NAME) FROM PERSON;


-- INITCAP
SELECT INITCAP(NAME) FROM PERSON;


-- LENGTH
SELECT NAME, LENGTH(NAME) FROM PERSON;


-- SUBSTR
SELECT SUBSTR(NAME, 1, 3) FROM PERSON;


